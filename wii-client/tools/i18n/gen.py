import os
HERE=os.path.dirname(os.path.abspath(__file__))
#!/usr/bin/env python3
# Generates wii-client/source/i18n_table.c from translations.py (dict: Spanish key -> [en,fr,de,it,nl,pt])
import sys,re,os
sys.path.insert(0,HERE+'')
from keys import keys
ks=keys()
entries=[]
for n in (1,2,3,4,5):
    ns={}; exec(open(HERE+f'/tr/p{n}.py',encoding='utf8').read(),ns); entries+=ns['P']
LANGS=['en','fr','de','it','nl','pt']
import json
from opencc import OpenCC
_occ=OpenCC('s2twp')
order=json.load(open(HERE+'/order.json'))
cjk={}
for n in (1,2,3,4):
    ns={}; exec(open(HERE+f'/cjk/c{n}.py',encoding='utf8').read(),ns)
    for t in ns['C']: cjk[t[0]]=t
def to_zt(z):
    t=_occ.convert(z)
    for a,b in (('二維碼','QR 碼'),('關注','追隨'),('愛好','愛好')): t=t.replace(a,b)
    return t
NOTO={'en':'Noto Sans CJK font (subset, SIL OFL 1.1)','fr':'police Noto Sans CJK (sous-ensemble, SIL OFL 1.1)','de':'Schrift Noto Sans CJK (Teilmenge, SIL OFL 1.1)','it':'font Noto Sans CJK (sottoinsieme, SIL OFL 1.1)','nl':'lettertype Noto Sans CJK (subset, SIL OFL 1.1)','pt':'fonte Noto Sans CJK (subconjunto, SIL OFL 1.1)'}
tr={}; used=set(); perr=[]
for e in entries:
    pre=e[0]; vals=list(e[1:])
    if len(vals)!=6: perr.append('BAD ENTRY '+repr(pre)); continue
    if pre in ks: k=pre
    else:
        m=[k for k in ks if k.startswith(pre)]
        if len(m)!=1: perr.append(f'PREFIX {pre!r} matches {len(m)}'); continue
        k=m[0]
    if k in tr: perr.append('DUP '+repr(k))
    tr[k]=vals
for e in perr: print(e)
_ord=sorted(ks,key=lambda x:x.encode('utf8'))
cjk_key={order[i][0]:cjk[i] for i in range(len(order))}
ns={}; exec(open(HERE+'/cjk/extra.py',encoding='utf8').read(),ns)
def find_cjk(k):
    if k in cjk_key: return cjk_key[k]
    for pre,v in ns['X'].items():
        if k.startswith(pre): return (None,)+tuple(v)
    for ok,v in cjk_key.items():
        if ok.startswith('Software: FFmpeg') and k.startswith('Software: FFmpeg'): return v
    return None
for k in _ord:
    if k in tr and len(tr[k])==6:
        c=find_cjk(k)
        if c is None: perr.append('NO CJK '+repr(k)); continue
        if k.startswith('Software: FFmpeg'):
            tr[k]=[ (v[:-2]+', '+NOTO[L]+'. ') if v.endswith('. ') else v for L,v in zip(LANGS,tr[k]) ]
        tr[k]=list(tr[k])+[c[1],c[2],to_zt(c[2]),c[3]]


spec=re.compile(r'%[-+ #0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|h|ll|l|z)?[diuxXsfcp%]')
def specs(s): return [x for x in spec.findall(s) if x!='%%']
errs=[]
CH={}
def cesc(s):
    out=''
    for ch in s.encode('latin-1' if all(ord(c)<256 for c in s) else 'utf8'):
        pass
    return None
def lit(s):
    # bytes: the app font is Latin-1 glyphs but strings are UTF-8 in the source
    b=s.encode('utf8'); o=''
    for c in b:
        if c==ord('"'): o+='\\"'
        elif c==ord('\\'): o+='\\\\'
        elif c==10: o+='\\n'
        elif 32<=c<127: o+=chr(c)
        else: o+='\\%03o'%c
    return '"'+o+'"'
ALLOWED=set(chr(c) for c in range(32,127))|set(chr(c) for c in range(160,256))|{'\n'}
rows=[]
for k in sorted(ks,key=lambda x:x.encode('utf8')):
    if k not in tr: errs.append('MISSING '+repr(k)); continue
    t=tr[k]
    if len(t)!=10: errs.append('BAD LEN '+repr(k)); continue
    for L,x in zip(LANGS+['ja','zh','zt','ko'],t):
        if specs(x)!=specs(k): errs.append(f'FORMAT {L}: {k!r} -> {x!r}')
        if x.count('\n')!=k.count('\n'): errs.append(f'NEWLINES {L}: {k!r} -> {x!r}')
        if x.count('%%')!=k.count('%%'): errs.append(f'PCT {L}: {k!r}')
        if L in ('ja','zh','zt','ko'):
            CH.setdefault(L,set()).update(c for c in x if ord(c)>255)
            bad=[c for c in x if ord(c)<256 and c not in ALLOWED]
        else: bad=[c for c in x if c not in ALLOWED]
        if bad: errs.append(f'GLYPH {L} {bad}: {x!r}')
        if re.search(r'\brc\d|\bRC\b',x): errs.append('RC '+x)
    rows.append((k,t))
extra=[k for k in tr if k not in ks]
if extra: print('UNUSED translations:',len(extra),file=sys.stderr)
for e in errs: print(e)
if errs and '--force' not in sys.argv: print(len(errs),'errors'); sys.exit(1)
with open(HERE+'/../../source/i18n_table.c','w') as f:
    f.write('/* Generated by tools/i18n/gen.py from translations.py - do not edit by hand.\n * Key = Spanish source text (sorted bytewise). Columns: en, es(key), fr, de, it, nl, pt. */\n#include "i18n.h"\ntypedef struct { const char *es; const char *t[LANG_COUNT]; } i18n_entry_t;\nconst i18n_entry_t i18n_table[] = {\n')
    for k,t in rows:
        en,fr,de,it,nl,pt,ja,zh,zt,ko=t
        f.write('{%s,{%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s}},\n'%(lit(k),lit(en),lit(k),lit(fr),lit(de),lit(it),lit(nl),lit(pt),lit(ja),lit(zh),lit(zt),lit(ko)))
    f.write('};\nconst int i18n_table_n = %d;\n'%len(rows))
print('wrote',len(rows),'entries')
NAMES={'ja':'日本語','zh':'简体中文','zt':'繁體中文','ko':'한국어'}
STREAM_NAMES='日本語한국어中文'
allc=set(''.join(NAMES.values())+STREAM_NAMES)
json.dump({'sets':{L:sorted(CH.get(L,set())) for L in NAMES},'names':sorted(allc),'bigtxt':{'ja':'探す','zh':'浏览','zt':to_zt('浏览'),'ko':'탐색'}},open(HERE+'/cjk/chars.json','w'),ensure_ascii=False)
for L in NAMES: print(L,len(CH.get(L,())),'glyphs')
