import os
HERE=os.path.dirname(os.path.abspath(__file__))
#!/usr/bin/env python3
# Builds wii-client/source/cjk_data.c: 4-bit alpha bitmaps of ONLY the CJK glyphs used by the app's JA/ZH/ZT/KO
# strings (+ the language names), rasterised from Noto Sans CJK (SIL OFL 1.1) at the UI sizes.
import json,sys
from PIL import Image,ImageDraw,ImageFont
D=json.load(open(HERE+'/cjk/chars.json'))
P='/usr/share/fonts/opentype/noto/NotoSansCJK-%s.ttc'
IDX={'ja':0,'ko':1,'zh':2,'zt':3}
# (name, weight, em px, base ascent of the Latin font it replaces, only-big-text?)
SIZES=[('r14','Regular',14,12,False),('r15','Regular',15,13,False),('b16','Bold',16,14,False),('b32','Bold',32,28,True)]
SETS=['names','ja','zh','zt','ko']
NAMEFONT={}
for L,nm in (('ja','日本語'),('zh','简体中文'),('zt','繁體中文'),('ko','한국어')):
    for ch in nm: NAMEFONT.setdefault(ch,L)
for ch in '日本語': NAMEFONT[ch]='ja'
for ch in '한국어': NAMEFONT[ch]='ko'
for ch in '中文': NAMEFONT[ch]='zh'
fcache={}
def font(w,idx,em):
    k=(w,idx,em)
    if k not in fcache: fcache[k]=ImageFont.truetype(P%w,em,index=idx,layout_engine=ImageFont.Layout.BASIC)
    return fcache[k]
def raster(ch,w,idx,em,asc):
    f=font(w,idx,em); pad=em
    im=Image.new('L',(em*3,em*3),0); d=ImageDraw.Draw(im)
    d.text((pad,pad+asc),ch,font=f,fill=255,anchor='ls')
    bb=im.getbbox()
    adv=max(1,int(round(f.getlength(ch))))
    if not bb: return (0,0,0,0,adv,b'')
    c=im.crop(bb); w_,h_=c.size
    px=[int(255*((a/255.0)**0.85)+0.5) for a in c.tobytes()]
    nib=[min(15,(a*15+127)//255) for a in px]
    if len(nib)%2: nib.append(0)
    data=bytes((nib[i]<<4)|nib[i+1] for i in range(0,len(nib),2))
    return (w_,h_,bb[0]-pad,bb[1]-pad,adv,data)
import struct,zlib
out=['/* Generated by tools/i18n/gen_cjk.py - do not edit. CJK glyph subset rasterised from Noto Sans CJK (SIL OFL 1.1, see licenses/).\n * Set 0 (language names) is stored plain; each language set is a zlib blob inflated into the heap only while that language is active. */\n#include "gfx.h"\n']
def build(S):
    sizes=[]
    for (sn,w,em,asc,bigonly) in SIZES:
        if S=='names': cs=D['names']
        elif bigonly: cs=D['bigtxt'][S]
        else: cs=D['sets'][S]
        cs=sorted(set(cs),key=ord)
        if bigonly and S=='names': cs=[]
        cps=[];gl=[];bits=bytearray()
        for ch in cs:
            L=NAMEFONT[ch] if S=='names' else S
            r=raster(ch,w,IDX[L],em,asc)
            cps.append(ord(ch)); gl.append((r[0],r[1],r[2],r[3],r[4],len(bits))); bits+=r[5]
        sizes.append((cps,gl,bytes(bits)))
    return sizes
# set 0: plain C arrays
sizes=build('names'); row=[]
for k,(cps,gl,bits) in enumerate(sizes):
    if not cps: row.append('{0,0,0,0}'); continue
    nm='names_%d'%k
    out.append('static const unsigned short %s_cp[]={%s};\n'%(nm,','.join(map(str,cps))))
    out.append('static const Glyph %s_g[]={%s};\n'%(nm,','.join('{%d,%d,%d,%d,%d,%d}'%g for g in gl)))
    out.append('static const unsigned char %s_b[]={%s};\n'%(nm,','.join(map(str,bits))))
    row.append('{%d,%s_cp,%s_g,%s_b}'%(len(cps),nm,nm,nm))
out.append('const CjkSet cjk_names[4]={%s};\n'%','.join(row))
# sets 1..4: blobs. Header: 4 x {n,cp_off,g_off,b_off} (u32 big endian), then data, each part 4-byte aligned.
zl=[];rl=[];tot=0
for si,S in enumerate(SETS[1:],1):
    sizes=build(S); parts=[]; hdr=[]; off=64
    body=b''
    def add(b):
        global body
        o=64+len(body); body+=b; body+=b'\0'*((-len(body))%4); return o
    for cps,gl,bits in sizes:
        co=add(struct.pack('>%dH'%len(cps),*cps)); go=add(b''.join(struct.pack('>hhhhhxxi',*g) for g in gl)); bo=add(bits)
        hdr.append(struct.pack('>IIII',len(cps),co,go,bo))
    raw=b''.join(hdr)+body
    z=zlib.compress(raw,9); zl.append(len(z)); rl.append(len(raw)); tot+=len(z)
    out.append('static const unsigned char cjk_z%d[]={%s};\n'%(si,','.join(map(str,z))))
out.append('const unsigned char *const cjk_zdata[4]={cjk_z1,cjk_z2,cjk_z3,cjk_z4};\nconst unsigned cjk_zlen[4]={%s};\nconst unsigned cjk_rawlen[4]={%s};\n'%(','.join(map(str,zl)),','.join(map(str,rl))))

# ---- shared fallback: JIS X 0208 level-1 kanji + GB2312 level-1 hanzi + KS X 1001 hangul + kana,
# rasterised at body size only (15px Regular). Inflated on first missing CJK code point.
def fallback_chars():
    s=set()
    for ku in range(16,48):
        for ten in range(1,95):
            try:
                ch=bytes([0xA0+ku,0xA0+ten]).decode('euc-jp')
                if len(ch)==1 and '\u4e00'<=ch<='\u9fff': s.add(ch)
            except Exception:
                pass
    for r in range(0xB0,0xD8):
        for c in range(0xA1,0xFF):
            try:
                ch=bytes([r,c]).decode('gb2312')
                if len(ch)==1 and '\u4e00'<=ch<='\u9fff': s.add(ch)
            except Exception:
                pass
    for r in range(0xB0,0xC9):
        for c in range(0xA1,0xFF):
            try:
                ch=bytes([r,c]).decode('euc-kr')
                if len(ch)==1 and '\uac00'<=ch<='\ud7a3': s.add(ch)
            except Exception:
                pass
    s |= set(chr(i) for i in list(range(0x3041,0x3097))+list(range(0x30A1,0x30FB))+[0x30FC,0x3005,0x3001,0x3002,0x30FB,0x300C,0x300D,0x300E,0x300F])
    s |= set('、。・「」『』（）【】…—ー！？〜〈〉《》')
    return sorted(s, key=ord)
def fb_idx(ch):
    if '\uac00'<=ch<='\ud7a3' or '\u1100'<=ch<='\u11ff': return 1
    return 0
fb=fallback_chars()
# 4 size slots, only body (index 1, Regular 15 / ascent 13) is filled
sizes_fb=[]
for si,(sn,w,em,asc,bigonly) in enumerate(SIZES):
    if si!=1:
        sizes_fb.append(([],[],b'')); continue
    cps=[];gl=[];bits=bytearray()
    for ch in fb:
        r=raster(ch,w,fb_idx(ch),em,asc)
        cps.append(ord(ch)); gl.append((r[0],r[1],r[2],r[3],r[4],len(bits))); bits+=r[5]
    sizes_fb.append((cps,gl,bytes(bits)))
body=b''; hdr=[]
def addfb(b):
    global body
    o=64+len(body); body+=b; body+=b'\0'*((-len(body))%4); return o
for cps,gl,bits in sizes_fb:
    if not cps:
        hdr.append(struct.pack('>IIII',0,0,0,0)); continue
    co=addfb(struct.pack('>%dH'%len(cps),*cps)); go=addfb(b''.join(struct.pack('>hhhhhxxi',*g) for g in gl)); bo=addfb(bits)
    hdr.append(struct.pack('>IIII',len(cps),co,go,bo))
raw=b''.join(hdr)+body
z=zlib.compress(raw,9)
out.append('const unsigned char cjk_fb_z[]={%s};\n'%(','.join(map(str,z))))
# expose with the names gfx.c expects
# (re-declare as the extern const — use the static array name cjk_fb_z already)
out.append('const unsigned cjk_fb_zlen=%d;\nconst unsigned cjk_fb_rawlen=%d;\n'%(len(z),len(raw)))
print('fallback chars',len(fb),'z',len(z),'raw',len(raw))

open(HERE+'/../../source/cjk_data.c','w').write(''.join(out))
print('compressed',zl,'raw',rl,'total z',tot)
